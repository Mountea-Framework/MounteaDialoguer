import fs from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const { parse } = createRequire(import.meta.url)('@babel/parser');
const generated = ['docs/technical/source-map-current.md', 'docs/technical/logic-index-current.md'];
const candidates = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { encoding: 'utf8', windowsHide: true }).split('\0').filter(Boolean);
const files = [];
for (const file of [...new Set([...candidates, ...generated])].sort()) {
	if (file.startsWith('.playwright-cli/') || file.startsWith('tmp/')) continue;
	if (generated.includes(file) || await fs.stat(file).then((stat) => stat.isFile(), () => false)) files.push(file);
}
const link = (file, line) => `[${file}${line ? `:${line}` : ''}](../../${file.replaceAll(' ', '%20')}${line ? `#L${line}` : ''})`;
const source = ['# Current source map', '', 'Generated by `node scripts/update-technical-indexes.mjs` from tracked and unignored source paths. Baseline history remains in [source-map.md](source-map.md); behavior and test evidence live in area guides and the [implementation ledger](implementation-progress.md). Private environment contents are never read. Generated builds, dependencies and local browser artifacts are excluded.', '', '| File | Current role |', '| --- | --- |'];
const logic = ['# Current callable index', '', 'Generated from current JavaScript syntax. Includes declarations, methods and callbacks; inclusion implies no runtime coverage. Baseline history remains in [logic-index.md](logic-index.md). Regenerate after code changes.', ''];
let functions = 0, codeFiles = 0;
for (const file of files) {
	const code = /\.(?:js|jsx|cjs|mjs)$/.test(file);
	const role = file.startsWith('tests/') ? 'Executable test/harness' : file.startsWith('scripts/') || file.startsWith('.github/') ? 'Tooling/release' : file.startsWith('electron/') ? 'Native runtime' : file.startsWith('src/') ? 'Renderer/data/domain' : file.startsWith('docs/') ? 'Technical guidance/evidence' : 'Configuration/assets/project support';
	source.push(`| ${file.startsWith('.env') ? `\`${file}\` (contents excluded)` : link(file)} | ${role} |`);
	if (!code) continue;
	codeFiles++;
	const ast = parse(await fs.readFile(file, 'utf8'), { sourceType: 'unambiguous', plugins: ['jsx'] });
	const entries = [];
	const label = (node) => node?.name || node?.value || node?.id?.name || node?.key?.name || node?.key?.value || '';
	const visit = (node, parent) => {
		if (!node || typeof node !== 'object') return;
		if (['FunctionDeclaration', 'FunctionExpression', 'ArrowFunctionExpression', 'ObjectMethod', 'ClassMethod', 'ClassPrivateMethod'].includes(node.type)) {
			const name = String(label(node) || label(parent) || `anonymous ${node.type}`).replaceAll('|', '\\|').replaceAll('`', '');
			entries.push(`- [${name}](../../${file.replaceAll(' ', '%20')}#L${node.loc.start.line}) — line ${node.loc.start.line}`);
			functions++;
		}
		for (const [key, value] of Object.entries(node)) {
			if (['loc', 'start', 'end', 'tokens', 'comments'].includes(key)) continue;
			if (Array.isArray(value)) value.forEach((child) => visit(child, node));
			else if (value?.type) visit(value, node);
		}
	};
	visit(ast);
	logic.push(`## ${file}`, '', link(file), '', ...(entries.length ? entries : ['No locally declared callable.']), '');
}
source.splice(4, 0, `Inventory: ${files.length} files; ${codeFiles} JavaScript-family files.`, '');
logic.splice(4, 0, `${functions} callables across ${codeFiles} code files.`, '');
await fs.writeFile(generated[0], source.join('\n') + '\n');
await fs.writeFile(generated[1], logic.join('\n') + '\n');
console.log(`Indexed ${files.length} files and ${functions} callables.`);
